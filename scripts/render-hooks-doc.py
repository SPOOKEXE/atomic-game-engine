#!/usr/bin/env python3
"""Write docs/engine/RENDER_HOOKS.md from docs/render-hooks.toml.

Usage:
    render-hooks-doc.py           write the page
    render-hooks-doc.py --check   fail if the page is stale, or if the toml and
                                  the hooks registered in code disagree

Hook limits are read from DataFactoryHookBind.hpp so the page never restates a
number by hand. Data capture channel names are read from DataCapture.cpp.
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/render-hooks.toml"
OUT = ROOT / "docs/engine/RENDER_HOOKS.md"
CHANNELS_CPP = ROOT / "mono.engine/render/src/DataCapture.cpp"
BIND_CPP = ROOT / "mono.engine/render/src/DataFactoryHookBind.cpp"


def code_channels():
    """Return (all channel names in enum order, names skipped at registration)."""
    text = CHANNELS_CPP.read_text()
    pairs = re.findall(r"case DataCaptureChannel::(\w+):\s*return \"(\w+)\";", text)
    by_enum = dict(pairs)
    skipped = re.findall(r"channel == DataCaptureChannel::(\w+)\) continue", BIND_CPP.read_text())
    return [name for _, name in pairs], {by_enum[e] for e in skipped}


def code_view_hooks():
    """Names of non-capture hooks registered with a literal name."""
    text = BIND_CPP.read_text()
    block = text[text.index("RegisterBuiltInViewMutationHooks() {"):]
    return set(re.findall(r'\.Name = core::Name\("([\w.]+)"\)', block))


def limits(header):
    """(name, value, comment) for each MAX_ constant in the hook header."""
    text = (ROOT / header).read_text()
    found = re.findall(r"((?:[ \t]*//[^\n]*\n)*)[ \t]*inline constexpr \w+ (MAX_\w+) = ([^;]+);", text)
    out = []
    for comment, name, value in found:
        lines = [line.strip().removeprefix("//").strip() for line in comment.strip().splitlines()]
        out.append((name, value.strip(), " ".join(lines)))
    return out


def para(text):
    return " ".join(text.split())


def render(data):
    owner = data["owner"]
    lines = [
        "# Render hooks",
        "",
        "<!-- Generated by `just render-hooks` from docs/render-hooks.toml. Edit that file. -->",
        "",
        para(owner["summary"]),
        "",
        # Plain paths: Doxygen indexes no sources or tests, so a link to one
        # would dangle on the docs site.
        f"- Owner: `{owner['type']}` in `{owner['header']}`, `{owner['source']}`",
        f"- Tests: `{owner['tests']}`",
        f"- Benchmark: `{owner['bench']}`",
        "- Adapters: " + ", ".join(f"`{a}`" for a in owner["adapters"]),
        "",
        "## Hooks",
        "",
        "| Name | Kind | Access | Node | Registered | Admitted | Runs at | Collected |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for hook in data["hook"]:
        lines.append(
            f"| `{hook['name']}` | {hook['kind']} | {hook['access']} | `{hook['node_kind']}` | "
            f"`{hook['registered']}` | {hook['admitted']} | {hook['observed']} | {hook['collected']} |"
        )
    for hook in data["hook"]:
        lines += ["", f"### `{hook['name']}`", "", para(hook["summary"])]
        if "mutates" in hook:
            lines += ["", "Mutates: " + ", ".join(f"`{f}`" for f in hook["mutates"]) + "."]
        if "channels" in hook:
            lines += ["", "| Hook | Channel |", "|---|---|"]
            for channel in hook["channels"]:
                lines.append(f"| `data_capture.{channel['name']}` | {channel['what']} |")
            for channel in hook.get("skipped", []):
                lines.append(f"| not registered: `{channel['name']}` | {channel['why']} |")
    lines += ["", "## Limits", "", "From the header, so these are always current.", "", "| Constant | Value | Meaning |", "|---|---|---|"]
    for name, value, comment in limits(owner["header"]):
        lines.append(f"| `{name}` | `{value}` | {comment} |")
    lines += ["", "## Rules", ""]
    for rule in data["rule"]:
        lines.append(f"- {rule['title']}. {para(rule['body'])}")
    lines += ["", "## Planned cleanup", ""]
    for item in data.get("planned", []):
        lines.append(f"- {item['title']}. {para(item['body'])}")
    return "\n".join(lines) + "\n"


def check_registry(data):
    """Errors where the toml and the code disagree on which hooks exist."""
    errors = []
    channels, skipped = code_channels()
    registered = {f"data_capture.{c}" for c in channels if c not in skipped} | code_view_hooks()
    listed = set()
    for hook in data["hook"]:
        if "channels" in hook:
            listed |= {f"data_capture.{c['name']}" for c in hook["channels"]}
            toml_skipped = {c["name"] for c in hook.get("skipped", [])}
            if toml_skipped != skipped:
                errors.append(f"skipped channels differ: toml {sorted(toml_skipped)} code {sorted(skipped)}")
        else:
            listed.add(hook["name"])
    for name in sorted(registered - listed):
        errors.append(f"registered in code, missing from toml: {name}")
    for name in sorted(listed - registered):
        errors.append(f"in toml, not registered in code: {name}")
    return errors


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = tomllib.loads(SOURCE.read_text())
    page = render(data)
    if not args.check:
        OUT.write_text(page)
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    errors = check_registry(data)
    if not OUT.exists() or OUT.read_text() != page:
        errors.append(f"{OUT.relative_to(ROOT)} is stale; run `just render-hooks`")
    for error in errors:
        print(f"render-hooks-check: {error}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
