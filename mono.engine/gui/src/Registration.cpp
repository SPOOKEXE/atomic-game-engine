		// A viewer-local facet still occupies its ordinary row after restore, but
		// its values must not survive a checkpoint. Keeping the component avoids
		// a module-specific post-load pass while every fresh value is derived by
		// the local layout, input, binding, or presentation pass.
		template <class T> void WriteTransientStates(core::ByteWriter &, const void *, size_t) {}

		template <class T> void ReadTransientStates(core::ByteReader &, void *destination, size_t count) {
			auto *states = static_cast<T *>(destination);
			for (size_t index = 0; index < count; index++) {
				states[index] = {};
			}
		}

		// Three components hold a `core::Name`, and a name's id is a counter
		// this process assigned in first-seen order. The generated byte
		// serialiser would write that counter, and a reading process would
		// resolve it to whatever string happened to take the same number -
		// which is not a corrupt file, it is a file that loads and is wrong.
		//
		// `scene`'s `WriteVisuals` says the same thing and carries the lesson
		// this repeats deliberately: **a field added to a type with a
		// hand-written serialiser crosses only if somebody remembers, and
		// nothing in the build checks.** So each pair below writes every field
		// of its struct in declaration order, and `gui/tests/Registration.cpp`
		// round-trips a fully-populated value rather than a default one - a
		// default-valued round trip passes whatever you forget.

		void WriteLabels(core::ByteWriter &writer, const void *source, size_t count) {
			const auto *labels = static_cast<const Label *>(source);
			for (size_t index = 0; index < count; index++) {
				const Label &label = labels[index];
				writer.WriteString(label.Text);
				writer.WriteFloat(label.Color.R);
				writer.WriteFloat(label.Color.G);
				writer.WriteFloat(label.Color.B);
				writer.WriteFloat(label.Transparency);
				writer.WriteInt32(label.Size);
				writer.WriteInt8(static_cast<int8_t>(label.Font));
				writer.WriteInt8(static_cast<int8_t>(label.XAlignment));
				writer.WriteInt8(static_cast<int8_t>(label.YAlignment));
				writer.WriteBool(label.Wrapped);
				writer.WriteBool(label.Scaled);
				writer.WriteInt8(static_cast<int8_t>(label.Truncate));
				writer.WriteFloat(label.StrokeColor.R);
				writer.WriteFloat(label.StrokeColor.G);
				writer.WriteFloat(label.StrokeColor.B);
				writer.WriteFloat(label.StrokeTransparency);
				writer.WriteFloat(label.LineHeight);

				// **Added at v0.18, in the same breath as the fields.** This
				// pair is exactly the discipline the comment above this function
				// exists to keep, and the reason it is written down twice.
				writer.WriteInt32(label.MaxVisible);
				writer.WriteBool(label.Rich);
			}
		}

		void ReadLabels(core::ByteReader &reader, void *destination, size_t count) {
			auto *labels = static_cast<Label *>(destination);
			for (size_t index = 0; index < count; index++) {
				Label &label = labels[index];
				label.Text = std::string(reader.ReadString());
				label.Color.R = reader.ReadFloat();
				label.Color.G = reader.ReadFloat();
				label.Color.B = reader.ReadFloat();
				label.Transparency = reader.ReadFloat();
				label.Size = reader.ReadInt32();
				label.Font = static_cast<FontFace>(reader.ReadInt8());
				label.XAlignment = static_cast<TextXAlignment>(reader.ReadInt8());
				label.YAlignment = static_cast<TextYAlignment>(reader.ReadInt8());
				label.Wrapped = reader.ReadBool();
				label.Scaled = reader.ReadBool();
				label.Truncate = static_cast<TextTruncate>(reader.ReadInt8());
				label.StrokeColor.R = reader.ReadFloat();
				label.StrokeColor.G = reader.ReadFloat();
				label.StrokeColor.B = reader.ReadFloat();
				label.StrokeTransparency = reader.ReadFloat();
				label.LineHeight = reader.ReadFloat();
				label.MaxVisible = reader.ReadInt32();
				label.Rich = reader.ReadBool();
			}
		}

