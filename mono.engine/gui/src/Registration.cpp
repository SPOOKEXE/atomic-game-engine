	void RegisterGuiComponents() {
		// Order is deliberate and not alphabetical, exactly as `scene`'s list
		// is: it decides component ids, which decide the order archetypes
		// iterate their columns in. **Add at the end.**
		//
		// The authored ones first, then the modifiers, then the one derived
		// component - which puts `Resolved` last, where a reader looking for
		// "what does the layout write" finds it without reading the rest.
		ecs::Components::Register<Element>("gui.Element");
		ecs::Components::Register<Background>("gui.Background");
		ecs::Components::Register<Label>("gui.Label", WriteLabels, ReadLabels);
		ecs::Components::Register<LabelPresentation>(
			"gui.LabelPresentation", WriteLabelPresentations, ReadLabelPresentations
		);
		ecs::Components::Register<Picture>("gui.Picture", WritePictures, ReadPictures);
		ecs::Components::Register<Button>("gui.Button");
		ecs::Components::Register<Scrolling>("gui.Scrolling");
		ecs::Components::Register<Entry>("gui.Entry", WriteEntries, ReadEntries);
		ecs::Components::Register<Layer>("gui.Layer");
		ecs::Components::Register<Canvas>(
			"gui.Canvas", WriteTransientStates<Canvas>, ReadTransientStates<Canvas>
		);
		ecs::Components::Register<CanvasTransform>(
			"gui.CanvasTransform", WriteTransientStates<CanvasTransform>, ReadTransientStates<CanvasTransform>
		);
		ecs::Components::Register<Surface>("gui.Surface");
		ecs::Components::Register<Billboard>("gui.Billboard");
		ecs::Components::Register<Group>("gui.Group");
		ecs::Components::Register<Viewport>("gui.Viewport");

		ecs::Components::Register<Padding>("gui.Padding");
		ecs::Components::Register<ListLayout>("gui.ListLayout");
		ecs::Components::Register<GridLayout>("gui.GridLayout");
		ecs::Components::Register<AspectRatio>("gui.AspectRatio");
		ecs::Components::Register<SizeLimits>("gui.SizeLimits");
		ecs::Components::Register<TextSizeLimits>("gui.TextSizeLimits");
		ecs::Components::Register<Corner>("gui.Corner");
		ecs::Components::Register<Stroke>("gui.Stroke");
		ecs::Components::Register<Scale>("gui.Scale");

		// **Derived, and it still has a stable registered name.** It is written
		// every frame by the layout pass and nothing replicates it - the
		// authority and the replica derive it identically from the same tree,
		// which is `scene::Visibility`'s argument - but a component with only
		// the automatic name `Components::Of<T>` mints from the compiler's
		// spelling is one two processes cannot agree on, and a snapshot taken
		// in a studio and restored in a test would be one of those two.
		ecs::Components::Register<Resolved>(
			"gui.Resolved", WriteTransientStates<Resolved>, ReadTransientStates<Resolved>
		);

		// **Derived too, and at the end for the reason the block below repeats.**
		// Written by whoever holds a camera and a world - `render` today - and
		// read by `CanvasFor`. A world that nobody draws never gets one, which is
		// exactly the case the authored fallback is for.
		ecs::Components::Register<SpatialCanvas>(
			"gui.SpatialCanvas", WriteTransientStates<SpatialCanvas>, ReadTransientStates<SpatialCanvas>
		);

		// **After `Resolved`, because the rule above is "add at the end".** The
		// order decides component ids, which decide the column order an
		// archetype iterates - so inserting this among the authored ones to keep
		// the grouping tidy would renumber everything after it and change what a
		// recording made before this version means.
		//
		// It carries an `ecs::Entity`, which crosses as an id and a generation
		// and needs no hand-written serialiser: unlike a `core::Name`, an entity
		// id means the same thing in the file it was written from and the world
		// it is read into, because that is what `ecs::Store::Load` remaps.
		ecs::Components::Register<GuiServiceState>(
			"gui.GuiServiceState", WriteTransientStates<GuiServiceState>, ReadTransientStates<GuiServiceState>
		);
		ecs::Components::Register<TextCompositionState>(
			"gui.TextCompositionState",
			WriteTransientStates<TextCompositionState>,
			ReadTransientStates<TextCompositionState>
		);

		// The 3D branch, at the end for the reason the rule above gives.
		ecs::Components::Register<Adornment>("gui.Adornment");
		ecs::Components::Register<AdornmentInteraction>("gui.AdornmentInteraction");
		ecs::Components::Register<SelectionOutline>("gui.SelectionOutline");
		ecs::Components::Register<HandleShape>("gui.HandleShape");

		// A modifier by nature, and still registered after the 3D branch:
		// the list is append-only because ids decide archetype column order,
		// so arriving at v0.17 puts it here rather than beside `Scale`.
		ecs::Components::Register<FlexItem>("gui.FlexItem");

		// Append-only, for the reason above. Trivially copyable despite holding
		// two sequences - `core::Sequence` is fixed-capacity precisely so that a
		// ramp can be a component, and its own header carries the argument.
		ecs::Components::Register<Gradient>("gui.Gradient", WriteGradients, ReadGradients);

		// Derived, so it belongs with `Resolved` by nature and at the end by
		// rule. Excluded from replication for `Resolved`'s exact reason: every
		// client recomputes it from the tree it was sent, and a bar sized on the
		// authority's canvas is a bar sized for somebody else's window.
		ecs::Components::Register<ScrollState>(
			"gui.ScrollState", WriteTransientStates<ScrollState>, ReadTransientStates<ScrollState>
		);

		// Authored, and still at the end because the list is append-only.
		ecs::Components::Register<Selection>("gui.Selection");
		ecs::Components::Register<TableLayout>("gui.TableLayout");
		ecs::Components::Register<PageLayout>("gui.PageLayout");
		ecs::Components::Register<DragDetector>("gui.DragDetector");

		// Derived and local, like `ScrollState` and for a sharper version of
		// its reason: this one holds a moment on *this* process's clock. A
		// client handed a server's timestamp would slide from wherever that
		// server's uptime happened to put it. Excluded from replication in
		// `replication::DefaultReplicatedComponents`; what crosses is
		// `PageLayout::CurrentPage`, and each end animates to it on its own
		// clock.
		ecs::Components::Register<PageMotion>(
			"gui.PageMotion", WriteTransientStates<PageMotion>, ReadTransientStates<PageMotion>
		);
		ecs::Components::Register<ScrollMotion>(
			"gui.ScrollMotion", WriteTransientStates<ScrollMotion>, ReadTransientStates<ScrollMotion>
		);

		// Local presentation policy authored by client scripts. The vector and
		// process-local names deliberately have no file or wire form.
		ecs::Components::Register<SettingsMenuExtensions>(
			"gui.SettingsMenuExtensions",
			WriteTransientStates<SettingsMenuExtensions>,
			ReadTransientStates<SettingsMenuExtensions>
		);

		// Appended because component ids are registration order. Each concrete
		// handle leaf owns only the dimensions its geometry consumes.
		ecs::Components::Register<BoxHandleShape>("gui.BoxHandleShape");
		ecs::Components::Register<SphereHandleShape>("gui.SphereHandleShape");
		ecs::Components::Register<CylinderHandleShape>("gui.CylinderHandleShape");
		ecs::Components::Register<LineHandleShape>("gui.LineHandleShape");
		ecs::Components::Register<ConeHandleShape>("gui.ConeHandleShape");
		ecs::Components::Register<HandlesShape>("gui.HandlesShape");
		ecs::Components::Register<ArcHandlesShape>("gui.ArcHandlesShape");

		// Appended because component ids decide archetype column order. This
		// separate row preserves LabelPresentation's older wire layout.
		ecs::Components::Register<LabelLocalizationArguments>(
			"gui.LabelLocalizationArguments", WriteLabelLocalizationArguments, ReadLabelLocalizationArguments
		);

		// The graph model is authored and crosses a save or replica. Its names
		// must be written as text rather than process-local ids, so the explicit
		// serializers live beside the other name-bearing GUI components.
		ecs::Components::Register<NodeCanvas>("gui.NodeCanvas");
		ecs::Components::Register<NodeCanvasNode>(
			"gui.NodeCanvasNode", WriteNodeCanvasNodes, ReadNodeCanvasNodes
		);
		ecs::Components::Register<NodeCanvasGroup>(
			"gui.NodeCanvasGroup", WriteNodeCanvasGroups, ReadNodeCanvasGroups
		);
		ecs::Components::Register<NodeCanvasPort>(
			"gui.NodeCanvasPort", WriteNodeCanvasPorts, ReadNodeCanvasPorts
		);
		ecs::Components::Register<NodeCanvasLink>(
			"gui.NodeCanvasLink", WriteNodeCanvasLinks, ReadNodeCanvasLinks
		);

		RegisterBindingComponents();
		RegisterVirtualCollectionComponents();
		RegisterModalComponents();

		// The authored clip writes its bounded tracks explicitly because a raw
		// representation would persist private capacity and process-local marker
		// names. The sampled state is rebuilt per view from explicit time.
		ecs::Components::Register<AnimationPlayback>(
			"gui.AnimationPlayback",
			WriteAnimationPlaybacks,
			ReadAnimationPlaybacks,
			static_cast<uint32_t>(
				1 + 4 + 4 + 4 + 1 + 1 + 1 + 4 +
				UIAnimation::MAXIMUM_TRACKS *
					(1 + 4 + PresentationTrack::MAXIMUM_KEYS * (4 + 1 + 4 * sizeof(float))) +
				4 + UIAnimation::MAXIMUM_MARKERS * (4 + UIAnimation::MAXIMUM_MARKER_NAME_BYTES + 4)
			)
		);
		ecs::Components::Register<PresentationState>(
			"gui.PresentationState",
			WriteTransientStates<PresentationState>,
			ReadTransientStates<PresentationState>
		);

		// The authored theme vocabulary uses custom byte forms because Names and
		// StyleSet's fixed capacities must survive a save independently of this
		// process's intern table. ResolvedStyle is local compile output.
		ecs::Components::Register<UITheme>("gui.UITheme", WriteUIThemes, ReadUIThemes);
		ecs::Components::Register<StyleClass>("gui.StyleClass", WriteStyleClasses, ReadStyleClasses);
		ecs::Components::Register<StyleDirect>("gui.StyleDirect");
		ecs::Components::Register<UIStyle>("gui.UIStyle", WriteUIStyles, ReadUIStyles);
		ecs::Components::Register<ThemeBinding>("gui.ThemeBinding");
		ecs::Components::Register<ResolvedStyle>(
			"gui.ResolvedStyle", WriteTransientStates<ResolvedStyle>, ReadTransientStates<ResolvedStyle>
		);

		// Appended because component identifiers are durable. A mask is authored
		// and serialisable, while its resolved operation is compile output.
		ecs::Components::Register<Mask>("gui.Mask");
	}
