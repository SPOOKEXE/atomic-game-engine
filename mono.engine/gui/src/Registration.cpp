		bool ValidLocalizedArgumentType(LocalizedArgumentType type) {
			return type == LocalizedArgumentType::String || type == LocalizedArgumentType::Number ||
				   type == LocalizedArgumentType::Date;
		}

		bool ValidLocalizedArgument(const LabelLocalizationArgument &argument) {
			return argument.Name.IsValid() && ValidLocalizedArgumentType(argument.Type) &&
				   argument.String.size() <= LabelLocalizationArguments::MAXIMUM_STRING_BYTES &&
				   (argument.Type != LocalizedArgumentType::Number || std::isfinite(argument.Number));
		}

		void WriteLabelLocalizationArguments(core::ByteWriter &writer, const void *source, size_t count) {
			const auto *arguments = static_cast<const LabelLocalizationArguments *>(source);
			for (size_t row = 0; row < count; row++) {
				const LabelLocalizationArguments &value = arguments[row];
				if (value.Count > LabelLocalizationArguments::MAXIMUM_ARGUMENTS) {
					throw std::length_error("too many localized label arguments");
				}
				writer.WriteUInt8(value.Count);
				for (size_t index = 0; index < value.Count; index++) {
					const LabelLocalizationArgument &argument = value.Values[index];
					if (!ValidLocalizedArgument(argument)) {
						throw std::length_error("invalid localized label argument");
					}
					for (size_t previous = 0; previous < index; previous++) {
						if (value.Values[previous].Name == argument.Name) {
							throw std::length_error("duplicate localized label argument");
						}
					}
					writer.WriteName(argument.Name);
					writer.WriteUInt8(static_cast<uint8_t>(argument.Type));
					switch (argument.Type) {
					case LocalizedArgumentType::String:
						writer.WriteString(argument.String);
						break;
					case LocalizedArgumentType::Number:
						writer.WriteDouble(argument.Number);
						break;
					case LocalizedArgumentType::Date:
						writer.WriteInt64(argument.UnixSeconds);
						break;
					}
				}
			}
		}

		void ReadLabelLocalizationArguments(core::ByteReader &reader, void *destination, size_t count) {
			auto *arguments = static_cast<LabelLocalizationArguments *>(destination);
			for (size_t row = 0; row < count; row++) {
				LabelLocalizationArguments decoded;
				decoded.Count = reader.ReadUInt8();
				if (decoded.Count > LabelLocalizationArguments::MAXIMUM_ARGUMENTS) {
					reader.Fail();
					continue;
				}
				for (size_t index = 0; index < decoded.Count; index++) {
					LabelLocalizationArgument &argument = decoded.Values[index];
					argument.Name = reader.ReadName();
					argument.Type = static_cast<LocalizedArgumentType>(reader.ReadUInt8());
					if (!argument.Name.IsValid() || !ValidLocalizedArgumentType(argument.Type)) {
						reader.Fail();
						break;
					}
					switch (argument.Type) {
					case LocalizedArgumentType::String:
						argument.String = std::string(reader.ReadString());
						if (argument.String.size() > LabelLocalizationArguments::MAXIMUM_STRING_BYTES)
							reader.Fail();
						break;
					case LocalizedArgumentType::Number:
						argument.Number = reader.ReadDouble();
						if (!std::isfinite(argument.Number)) reader.Fail();
						break;
					case LocalizedArgumentType::Date:
						argument.UnixSeconds = reader.ReadInt64();
						break;
					}
					for (size_t previous = 0; previous < index; previous++) {
						if (decoded.Values[previous].Name == argument.Name) reader.Fail();
					}
				}
				if (!reader.Failed()) arguments[row] = std::move(decoded);
			}
		}

		void WriteStyleSet(core::ByteWriter &writer, const StyleSet &set) {
			writer.WriteUInt32(static_cast<uint32_t>(set.Declarations().size()));
			for (const StyleDeclaration &declaration : set.Declarations()) {
				writer.WriteName(declaration.Name);
				writer.WriteUInt8(static_cast<uint8_t>(declaration.Value.Type));
				if (declaration.Value.Type == StyleValueType::Color) {
					writer.WriteFloat(declaration.Value.Color.R);
					writer.WriteFloat(declaration.Value.Color.G);
					writer.WriteFloat(declaration.Value.Color.B);
				} else {
					writer.WriteFloat(declaration.Value.Number);
				}
			}
		}

		bool ReadStyleSet(core::ByteReader &reader, StyleSet &set) {
			set = {};
			const uint32_t count = reader.ReadUInt32();
			if (count > StyleSet::MAXIMUM_DECLARATIONS) {
				reader.Fail();
				return false;
			}
			for (uint32_t index = 0; index < count; index++) {
				StyleDeclaration declaration;
				declaration.Name = reader.ReadName();
				declaration.Value.Type = static_cast<StyleValueType>(reader.ReadUInt8());
				if (declaration.Value.Type == StyleValueType::Color) {
					declaration.Value.Color = {reader.ReadFloat(), reader.ReadFloat(), reader.ReadFloat()};
				} else if (declaration.Value.Type == StyleValueType::Number) {
					declaration.Value.Number = reader.ReadFloat();
				} else {
					reader.Fail();
					return false;
				}
				if (!set.Set(declaration)) {
					reader.Fail();
					return false;
				}
			}
			return true;
		}

