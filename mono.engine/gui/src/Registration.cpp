		void ReadStyleClasses(core::ByteReader &reader, void *destination, size_t count) {
			auto *classes = static_cast<StyleClass *>(destination);
			for (size_t index = 0; index < count; index++) {
				classes[index] = {};
				const uint32_t names = reader.ReadUInt32();
				if (names > StyleClasses::MAXIMUM_CLASSES) {
					reader.Fail();
					continue;
				}
				for (uint32_t name = 0; name < names; name++) {
					if (!classes[index].Names.Add(reader.ReadName())) {
						reader.Fail();
					}
				}
			}
		}

		void WriteUIStyles(core::ByteWriter &writer, const void *source, size_t count) {
			const auto *styles = static_cast<const UIStyle *>(source);
			for (size_t index = 0; index < count; index++) {
				writer.WriteName(styles[index].Rule.Class);
				writer.WriteUInt8(static_cast<uint8_t>(styles[index].Rule.State));
				WriteStyleSet(writer, styles[index].Rule.Declarations);
			}
		}

		void ReadUIStyles(core::ByteReader &reader, void *destination, size_t count) {
			auto *styles = static_cast<UIStyle *>(destination);
			for (size_t index = 0; index < count; index++) {
				styles[index].Rule.Class = reader.ReadName();
				styles[index].Rule.State = static_cast<StyleState>(reader.ReadUInt8());
				if ((static_cast<uint8_t>(styles[index].Rule.State) & ~static_cast<uint8_t>(0x3f)) != 0) {
					reader.Fail();
				}
				(void)ReadStyleSet(reader, styles[index].Rule.Declarations);
			}
		}

		void WritePresentationValue(core::ByteWriter &writer, const PresentationValue &value) {
			writer.WriteUInt8(static_cast<uint8_t>(value.Type));
			switch (value.Type) {
			case PresentationValueType::Color:
				writer.WriteFloat(value.Color.R);
				writer.WriteFloat(value.Color.G);
				writer.WriteFloat(value.Color.B);
				return;
			case PresentationValueType::Number:
				writer.WriteFloat(value.Number);
				return;
			case PresentationValueType::UDim2:
				writer.WriteFloat(value.UDim2.X.Scale);
				writer.WriteFloat(value.UDim2.X.Offset);
				writer.WriteFloat(value.UDim2.Y.Scale);
				writer.WriteFloat(value.UDim2.Y.Offset);
				return;
			}
		}

		PresentationValue ReadPresentationValue(core::ByteReader &reader) {
			PresentationValue value;
			value.Type = static_cast<PresentationValueType>(reader.ReadUInt8());
			switch (value.Type) {
			case PresentationValueType::Color:
				value.Color = core::Color3{reader.ReadFloat(), reader.ReadFloat(), reader.ReadFloat()};
				break;
			case PresentationValueType::Number:
				value.Number = reader.ReadFloat();
				break;
			case PresentationValueType::UDim2:
				value.UDim2 = core::UDim2{
					reader.ReadFloat(), reader.ReadFloat(), reader.ReadFloat(), reader.ReadFloat()
				};
				break;
			default:
				reader.Fail();
				break;
			}
			return value;
		}

		void WriteAnimationPlaybacks(core::ByteWriter &writer, const void *source, size_t count) {
			const auto *playbacks = static_cast<const AnimationPlayback *>(source);
			for (size_t index = 0; index < count; index++) {
				const AnimationPlayback &playback = playbacks[index];
				const core::TweenInfo &tween = playback.Clip.Tween;
				writer.WriteBool(playback.Playing);
				writer.WriteFloat(tween.Time);
				writer.WriteFloat(tween.DelayTime);
				writer.WriteInt32(tween.RepeatCount);
				writer.WriteUInt8(static_cast<uint8_t>(tween.Style));
				writer.WriteUInt8(static_cast<uint8_t>(tween.Direction));
				writer.WriteBool(tween.Reverses);
				writer.WriteUInt32(static_cast<uint32_t>(playback.Clip.Tracks().size()));
				for (const PresentationTrack &track : playback.Clip.Tracks()) {
					writer.WriteUInt8(static_cast<uint8_t>(track.Property));
					writer.WriteUInt32(static_cast<uint32_t>(track.Keys().size()));
					for (const PresentationKey &key : track.Keys()) {
						writer.WriteFloat(key.Time);
						WritePresentationValue(writer, key.Value);
					}
				}
				writer.WriteUInt32(static_cast<uint32_t>(playback.Clip.Markers().size()));
				for (const AnimationMarker &marker : playback.Clip.Markers()) {
					writer.WriteName(marker.Name);
					writer.WriteFloat(marker.Time);
				}
			}
		}

		void ReadAnimationPlaybacks(core::ByteReader &reader, void *destination, size_t count) {
			auto *playbacks = static_cast<AnimationPlayback *>(destination);
			for (size_t index = 0; index < count; index++) {
				AnimationPlayback playback;
				playback.StartedAt = -1.0;
				playback.Playing = reader.ReadBool();
				core::TweenInfo &tween = playback.Clip.Tween;
				tween.Time = reader.ReadFloat();
				tween.DelayTime = reader.ReadFloat();
				tween.RepeatCount = reader.ReadInt32();
				tween.Style = static_cast<core::EasingStyle>(reader.ReadUInt8());
				tween.Direction = static_cast<core::EasingDirection>(reader.ReadUInt8());
				tween.Reverses = reader.ReadBool();

				const uint32_t tracks = reader.ReadUInt32();
				if (tracks > UIAnimation::MAXIMUM_TRACKS) {
					reader.Fail();
				}
				for (uint32_t trackIndex = 0; trackIndex < tracks && !reader.Failed(); trackIndex++) {
					PresentationTrack track;
					track.Property = static_cast<PresentationProperty>(reader.ReadUInt8());
					const uint32_t keys = reader.ReadUInt32();
					if (keys > PresentationTrack::MAXIMUM_KEYS) {
						reader.Fail();
						break;
					}
					for (uint32_t keyIndex = 0; keyIndex < keys && !reader.Failed(); keyIndex++) {
						if (!track.Add(PresentationKey{reader.ReadFloat(), ReadPresentationValue(reader)})) {
							reader.Fail();
						}
					}
					if (!reader.Failed() && !playback.Clip.AddTrack(track)) {
						reader.Fail();
					}
				}

				const uint32_t markers = reader.ReadUInt32();
				if (markers > UIAnimation::MAXIMUM_MARKERS) {
					reader.Fail();
				}
				for (uint32_t markerIndex = 0; markerIndex < markers && !reader.Failed(); markerIndex++) {
					const std::string_view name = reader.ReadString();
					if (name.size() > UIAnimation::MAXIMUM_MARKER_NAME_BYTES ||
						!playback.Clip.AddMarker(AnimationMarker{core::Name(name), reader.ReadFloat()})) {
						reader.Fail();
					}
				}

				PresentationOverrides sampled;
				if (!reader.Failed() && !SamplePresentation(playback.Clip, 0.0, sampled)) {
					reader.Fail();
				}
				playbacks[index] = reader.Failed() ? AnimationPlayback{} : playback;
			}
		}

		// **`gui.Gradient` is here for a different reason from the three above,
		// and it is a size rather than a correctness one.**
		//
		// A `core::ColorSequence` is twenty keypoint slots and a count, and a
		// `core::NumberSequence` is twenty more - 656 of the component's 672
		// bytes. The generated writer copies the object representation, so every
		// gradient in every world wrote all forty slots into every save and
		// every replication delta, whatever `Count` said. **A default two-stop
		// gradient is thirty-two meaningful bytes of ramp**, and it was costing
		// 656.
		//
		// So this writes `Count` and then that many stops, exactly as
		// `effects`'s ribbon pair does for the same two types. `Sequence::Add`
		// on the way back in is what keeps a hostile file from claiming a count
		// past the capacity.
		void WriteRamp(core::ByteWriter &writer, const core::ColorSequence &sequence) {
			writer.WriteUInt32(sequence.Count);
			for (uint32_t stop = 0; stop < sequence.Count; stop++) {
				writer.WriteFloat(sequence.Keypoints[stop].Time);
				writer.WriteFloat(sequence.Keypoints[stop].Value.R);
				writer.WriteFloat(sequence.Keypoints[stop].Value.G);
				writer.WriteFloat(sequence.Keypoints[stop].Value.B);
			}
		}

		void ReadRamp(core::ByteReader &reader, core::ColorSequence &sequence) {
			sequence = core::ColorSequence{};
			const uint32_t stops = reader.ReadUInt32();
			for (uint32_t stop = 0; stop < stops && !reader.Failed(); stop++) {
				const float at = reader.ReadFloat();
				const float red = reader.ReadFloat();
				const float green = reader.ReadFloat();
				const float blue = reader.ReadFloat();
				(void)sequence.Add(core::ColorKeypoint{at, core::Color3{red, green, blue}});
			}
		}

		void WriteCurve(core::ByteWriter &writer, const core::NumberSequence &sequence) {
			writer.WriteUInt32(sequence.Count);
			for (uint32_t stop = 0; stop < sequence.Count; stop++) {
				writer.WriteFloat(sequence.Keypoints[stop].Time);
				writer.WriteFloat(sequence.Keypoints[stop].Value);
				writer.WriteFloat(sequence.Keypoints[stop].Envelope);
			}
		}

		void ReadCurve(core::ByteReader &reader, core::NumberSequence &sequence) {
			sequence = core::NumberSequence{};
			const uint32_t stops = reader.ReadUInt32();
			for (uint32_t stop = 0; stop < stops && !reader.Failed(); stop++) {
				const float at = reader.ReadFloat();
				const float value = reader.ReadFloat();
				const float envelope = reader.ReadFloat();
				(void)sequence.Add(core::NumberKeypoint{at, value, envelope});
			}
		}

		void WriteGradients(core::ByteWriter &writer, const void *source, size_t count) {
			const auto *gradients = static_cast<const Gradient *>(source);
			for (size_t index = 0; index < count; index++) {
				const Gradient &gradient = gradients[index];
				WriteRamp(writer, gradient.Color);
				WriteCurve(writer, gradient.Transparency);
				writer.WriteFloat(gradient.Offset.X);
				writer.WriteFloat(gradient.Offset.Y);
				writer.WriteFloat(gradient.Rotation);
				writer.WriteBool(gradient.Enabled);
			}
		}

		void ReadGradients(core::ByteReader &reader, void *destination, size_t count) {
			auto *gradients = static_cast<Gradient *>(destination);
			for (size_t index = 0; index < count; index++) {
				Gradient &gradient = gradients[index];
				ReadRamp(reader, gradient.Color);
				ReadCurve(reader, gradient.Transparency);
				gradient.Offset.X = reader.ReadFloat();
				gradient.Offset.Y = reader.ReadFloat();
				gradient.Rotation = reader.ReadFloat();
				gradient.Enabled = reader.ReadBool();
			}
		}

