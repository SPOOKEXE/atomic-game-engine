	std::span<const std::byte> Bytes(const auto &container) {
		return {
			reinterpret_cast<const std::byte *>(container.data()),
			reinterpret_cast<const std::byte *>(container.data()) + container.size()
		};
	}

	// An ID3v2 header declaring `bodyBytes` of tag, syncsafe.
	std::vector<uint8_t> Id3v2(size_t bodyBytes, uint8_t flags = 0) {
		std::vector<uint8_t> tag{'I', 'D', '3', 4, 0, flags};
		tag.push_back(static_cast<uint8_t>((bodyBytes >> 21) & 0x7F));
		tag.push_back(static_cast<uint8_t>((bodyBytes >> 14) & 0x7F));
		tag.push_back(static_cast<uint8_t>((bodyBytes >> 7) & 0x7F));
		tag.push_back(static_cast<uint8_t>(bodyBytes & 0x7F));
		return tag;
	}
