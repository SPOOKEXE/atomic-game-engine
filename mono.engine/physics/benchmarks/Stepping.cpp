// A whole physics tick, and the scenes that make one go wrong.
//
// **The other four suites here each measure one phase, and a tick is not the
// sum of them.** `Broadphase.cpp` knows what building the pair list costs,
// `NarrowPhase.cpp` what generating a manifold costs, `Solver.cpp` what a
// contact costs to solve and `Integrate.cpp` what stepping a body costs. What
// none of them can say is what a *frame* of physics costs, because each of the
// phases feeds the next: a broad phase that produces twice the pairs makes the
// narrow phase do twice the work and the solver do more than twice, and the
// only place that compounding is visible is a row that runs all of them.
//
// So every row here runs the tick the scheduler actually registers, in the order
// `Pipeline.cpp` composes it - integrate, sweep the fast bodies, sync the index,
// broad phase, narrow phase, solve, publish - and changes only the *scene*.
//
// **The scene shapes are the point, not the body count.** Physics does not get
// slow because a world is large; it gets slow because of what is in it, and the
// cases that hurt are cases a game reaches by accident:
//
// - **Everything in one pile.** A broad-phase grid is a constant factor right up
//   until every body lands in one cell, at which point the pair list is
//   quadratic and the narrow phase inherits it. A game reaches this by dropping
//   a crate spawner in a corner and forgetting about it.
// - **Everything asleep.** A steady world is mostly bodies that have not moved
//   for a second, and the whole reason the resting list exists is to keep them
//   out of the solve. Whether that actually saves anything is a claim nothing
//   here checked before this file.
// - **Everything woken every tick.** The other side of the same claim, and what
//   a script that writes a velocity to every body per tick produces.
// - **Fast bodies.** `SweepFastBodies` runs a swept test for anything moving far
//   enough to tunnel, and it runs between the integrate and the index rebuild
//   where nothing was measuring it.
//
// **The sleep pair is the most valuable rows in the file, and they came out
// flat.** A sixteen-thousand-body world in which every single body is asleep
// ticks at about what the same world costs with the resting list emptied before
// every tick - as measured the settled one is if anything the dearer of the two.
//
// That is not a bug in the resting list, it is what the resting list *is*.
// `Solve.cpp` says so at the line that uses it: "Asleep is immovable for this
// tick, which is the whole benefit." An asleep body is pinned, not removed - its
// contacts are still generated by the narrow phase and still swept by every
// solver iteration, they simply cannot move it. So a settled world pays the full
// contact cost of a moving one and saves only the integration.
//
// The four phase rows below are what turn that from a surprise into a number: on
// this scene the solve is around sixty per cent of a tick and the broad and
// narrow phases together are under fifteen. Whatever is worth doing about a
// settled world has to come out of the solve's manifold sweeps - skipping a
// contact whose two bodies are both asleep - and not out of skipping
// integration, which is already what happens and is already not where the time
// is.
//
// Every scene is built once, ticked a few times so the warm start is warm and
// the resting list has settled, and then measured. A first tick is the one tick
// a game never spends most of its time in.

