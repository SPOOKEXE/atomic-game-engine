	std::span<const std::byte> Bytes(std::span<const uint8_t> raw) {
		return {reinterpret_cast<const std::byte *>(raw.data()), raw.size()};
	}

	std::span<const std::byte> Bytes(std::string_view text) {
		return {reinterpret_cast<const std::byte *>(text.data()), text.size()};
	}

	ImportedModel Imported(ModelFormat format, std::span<const std::byte> bytes) {
		ImportedModel model;
		std::string failure;
		REQUIRE(ReadModel(format, bytes, model, failure));
		CHECK(failure.empty());
		REQUIRE(model.Mesh.IsValid());
		return model;
	}

	// The face normal a triangle's winding implies, which is the thing a
	// mirrored import gets wrong.
	std::array<float, 3> FaceNormal(const engine::assets::MeshData &mesh, size_t triangle) {
		const float *a = mesh.Vertices[mesh.Indices[triangle * 3]].Position;
		const float *b = mesh.Vertices[mesh.Indices[triangle * 3 + 1]].Position;
		const float *c = mesh.Vertices[mesh.Indices[triangle * 3 + 2]].Position;

		const float first[3] = {b[0] - a[0], b[1] - a[1], b[2] - a[2]};
		const float second[3] = {c[0] - a[0], c[1] - a[1], c[2] - a[2]};
		return {
			first[1] * second[2] - first[2] * second[1],
			first[2] * second[0] - first[0] * second[2],
			first[0] * second[1] - first[1] * second[0],
		};
	}
