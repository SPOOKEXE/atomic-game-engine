	std::span<const std::byte> Bytes(std::span<const uint8_t> raw) {
		return {reinterpret_cast<const std::byte *>(raw.data()), raw.size()};
	}

	// One pixel, as four numbers a failure message can print.
	struct Pixel {
		int R = 0, G = 0, B = 0, A = 0;

		bool operator==(const Pixel &) const = default;
	};

	Pixel At(const TextureData &image, uint32_t column, uint32_t row) {
		const size_t offset = (static_cast<size_t>(row) * image.Width + column) * 4;
		return {
			static_cast<int>(image.Pixels[offset]),
			static_cast<int>(image.Pixels[offset + 1]),
			static_cast<int>(image.Pixels[offset + 2]),
			static_cast<int>(image.Pixels[offset + 3]),
		};
	}

	TextureData Decoded(std::span<const uint8_t> raw) {
		TextureData image;
		std::string failure;
		REQUIRE(ReadImage(Bytes(raw), image, failure));
		CHECK(failure.empty());
		REQUIRE(image.IsValid());
		return image;
	}
